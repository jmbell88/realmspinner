def _small(name: str = "explosion"):
    rec = presets.load(name)
    return dataclasses.replace(rec, width=24, height=24, supersample=1)


def test_a_second_effects_tag_suffix_survives_save_and_reload(tmp_path):
    # inker-flourish-04: the suffix was chosen at insert and never written, so a
    # reloaded second effect regenerated by plain name and rewrote the first.
    doc = Document.blank(24, 24)
    a = doc.insert_flourish(B.bake(_small()))
    b = doc.insert_flourish(B.bake(_small()))
    assert doc.flourish_state(b).tag_suffix == "_2"
    path = tmp_path / "fx.ora"
    ora.write_ora(doc, path)
    back = ora.read_ora(path)
    suffixes = sorted(state.tag_suffix for state in back.flourish.values())
    assert suffixes == ["", "_2"]
    first_uid = next(u for u, s in back.flourish.items() if s.tag_suffix == "")
    second_uid = next(u for u, s in back.flourish.items() if s.tag_suffix == "_2")
    before = {t.name: (t.start, t.end) for t in back.anim.tags}
    rec = back.flourish_state(second_uid).recipe
    phases = list(rec.phases)
    phases[0] = dataclasses.replace(phases[0], frames=phases[0].frames + 3)
    back.apply_flourish(second_uid, B.bake(dataclasses.replace(rec, phases=tuple(phases))))
    after = {t.name: (t.start, t.end) for t in back.anim.tags}
    names = [t.name for t in back.anim.tags]
    assert len(names) == len(set(names)), "a reload must not make the tags collide"
    for name, span in before.items():
        if not name.endswith("_2"):
            assert after[name] == span, f"the first effect's {name} moved"
    assert first_uid != second_uid and a != b


def test_an_aseprite_slice_hanging_off_the_canvas_is_fitted_on_import():
    # inker-sheets-02, the .aseprite half: ``fit_slices`` ran in the .ora
    # reader only, so an Aseprite slice that hangs off the canvas kept its raw
    # rectangle and exported a wrapped crop.
    doc = Document.blank(8, 8)
    doc.slices.append(
        Slice(name="wide", bounds=(-4, -4, 20, 20), center=(15, 15, 19, 19))
    )
    back, _warnings = asein.document_from_aseprite(aseout.aseprite_bytes(doc))
    (entry,) = back.slices
    assert entry.bounds == (0, 0, 8, 8)
    x0, y0, x1, y1 = entry.bounds
    if entry.center is not None:
        cx0, cy0, cx1, cy1 = entry.center
        assert x0 <= cx0 <= cx1 <= x1 and y0 <= cy0 <= cy1 <= y1


# -- inker-40: the op door, not only the popup, holds the ceiling ---------------


def test_convert_layer_to_tilemap_refuses_a_grid_past_the_kernel_ceiling():
    # inker-panes-03: the tile-size popup greyed Convert past the ceiling, but
    # ``convert_layer_to_tilemap`` itself cut any grid in a Python loop, so every
    # other caller still froze the frame thread.
    import pytest

    from realmspinner.kernels.pixel import _doc_tiles

    side = 300  # 1x1 tiles -> 90,000 cells, past the 65,536 ceiling
    doc = Document.blank(side, side)
    layer_uid = doc.stack.active.uid
    with pytest.raises(ValueError, match="cells"):
        doc.convert_layer_to_tilemap(layer_uid, 1, 1)
    assert doc.stack.active.uid == layer_uid
    assert doc.tilesets == []
    assert doc.convert_layer_to_tilemap(layer_uid, 8, 8) is True
    assert _doc_tiles.MAX_TILE_CELLS == 65_536


def test_the_tile_popups_ceiling_is_the_kernels_own_constant():
    from realmspinner.kernels.pixel import _doc_tiles
    from realmspinner.studio.modes.inker.ui.panes import tiles as inker_tiles

    assert inker_tiles.MAX_TILE_CELLS is _doc_tiles.MAX_TILE_CELLS


# -- inker-72: a walk bake lands only on the session it was cut from -------------


def test_a_walk_bake_does_not_land_after_walk_was_left_and_entered_again():
    from modes.inker.test_walk_session import _rigged, _scene
    from realmspinner.studio.modes.inker import mode as inker_mode
    from realmspinner.studio.modes.inker import walk as inker_walk

    ctx, tab = _scene()
    first = _rigged(ctx, tab)
    # The ctx double runs a task inline and keeps no queue: collect the work
    # instead, so the landing can be delayed as the real queue delays it.
    answers: list = []
    ctx.submit = lambda key, fn, *a, **k: answers.append((key, fn)) or True
    assert inker_walk.bake(ctx, tab) is True
    key, work = answers[0]
    result = work()
    # Walk is left and entered again while the bake ran: a *new* session is open.
    inker_walk.cancel(ctx, tab)
    inker_walk.open_session(ctx, tab)
    assert ctx.state.inker.walk is not first
    tabs_before = len(ctx.state.inker.docs)
    from types import SimpleNamespace

    inker_mode.on_task_done(ctx, SimpleNamespace(key=key, result=result))
    assert ctx.state.inker.walk is not None, "the old rig's bake closed the new session"
    assert len(ctx.state.inker.docs) == tabs_before


def test_a_walk_bake_lands_on_the_session_it_was_cut_from():
    from types import SimpleNamespace

    from modes.inker.test_walk_session import _rigged, _scene
    from realmspinner.studio.modes.inker import mode as inker_mode
    from realmspinner.studio.modes.inker import walk as inker_walk

    ctx, tab = _scene()
    session = _rigged(ctx, tab)
    answers: list = []
    ctx.submit = lambda key, fn, *a, **k: answers.append((key, fn)) or True
    assert inker_walk.bake(ctx, tab) is True
    key, work = answers[0]
    result = work()
    assert set(result) == {"doc", "session"} and result["session"] is session
    inker_mode.on_task_done(ctx, SimpleNamespace(key=key, result=result))
    assert ctx.state.inker.walk is None
    assert any(t.title.endswith("walk") for t in ctx.state.inker.docs)


