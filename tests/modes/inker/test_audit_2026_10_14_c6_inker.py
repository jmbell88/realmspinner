def test_the_onion_tint_edit_converts_the_list_imgui_returns(monkeypatch):
    import contextlib
    from types import SimpleNamespace

    from _ui_context import imgui_context

    from realmspinner.studio import controls
    from realmspinner.studio.modes.inker.ui.panes import timeline

    state = SimpleNamespace(
        onion_tint_back=0x112233,
        onion_tint_forward=0x445566,
        onion_falloff=1.0,
        onion_in_front=False,
        onion_wrap_tag=False,
    )
    monkeypatch.setattr(
        controls, "menu_popup", lambda name: contextlib.nullcontext(True)
    )
    monkeypatch.setattr(
        controls, "color_edit4", lambda *a, **k: (True, [1.0, 0.5, 0.0, 1.0])
    )
    with imgui_context(monkeypatch) as imgui:
        imgui.new_frame()
        imgui.begin("x")
        timeline._onion_more(state)
        imgui.end()
        imgui.end_frame()
    # list -> 8-bit channels; ``value.x`` raised AttributeError before.
    assert state.onion_tint_back == (255 << 16) | (128 << 8) | 0
    assert state.onion_tint_forward == (255 << 16) | (128 << 8) | 0


# -- inker-flourish-16's sibling: the regeneration poll ---------------------------


def _inpaint_ctx(monkeypatch):
    from types import SimpleNamespace

    from modes.inker.test_audit_2026_10_14_f31 import _inpaint_session

    bridge, ctx, state, tab, pending = _inpaint_session(monkeypatch)
    reads: list = []

    class Store:
        def get(self, job_id):
            reads.append(job_id)
            return {"status": "failed", "error": "out of memory"}

    submitted: list = []
    ctx.svc = SimpleNamespace(store=Store())
    ctx.submit = lambda key, fn, *a, **k: submitted.append((key, fn, a, k)) or True
    return bridge, ctx, state, pending, reads, submitted


def test_poll_inpaint_reads_the_job_store_off_the_frame_thread(monkeypatch):
    from types import SimpleNamespace

    from realmspinner.studio.modes.inker import mode as inker_mode

    bridge, ctx, state, pending, reads, submitted = _inpaint_ctx(monkeypatch)
    pending["job_id"] = "j"
    pending["next_poll"] = 0.0
    bridge.poll_inpaint(ctx)
    assert reads == [], "the store was queried on the calling (frame) thread"
    assert len(submitted) == 1
    key, fn, args, kwargs = submitted[0]
    result = fn(*args, **kwargs)  # the task thread's half
    assert reads == ["j"]
    inker_mode.on_task_done(ctx, SimpleNamespace(key=key, result=result, error=None))
    assert state.inpaint_pending is None
    assert ctx.toasts[-1][0].startswith("The regeneration failed: out of memory")
